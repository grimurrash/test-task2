"""Нормализация путей и команд перед проверкой.

Внешнее ревью показало, чего стоит наивное сравнение строк: `$HOME/.aws/credentials`
не совпадал с шаблоном `~/.aws/`, а `> "../../outside/file"` проходил мимо проверки
границ. Регулярка сравнивала то, что написано, а не то, куда команда попадёт.

issue #43: обратная сторона той же строгости — восемь известных ложных отказов
за день, все одного класса: путеподобная строка **упомянута**, а не использована.
Здесь разбирается класс, а не случаи. Правило разбора одно: сужать по структуре
команды (тело heredoc, чужая файловая система, форма токена), а не по содержимому
пути — содержимое подделывается, структура нет. На каждое сужение в
`scripts/test_hooks.py` стоит парная проверка, что настоящий выход наружу
по-прежнему отклоняется; без неё сужение незаметно становится ослаблением.
"""
import os
import re
import shlex

HOME = os.path.expanduser("~")

# ─────────────────────────────────────────────────────────────────────────────
# Разбор команды: токенами, а не шаблонами.
#
# Два круга внешнего ревью показали границу регулярок. Каждый круг закрывал
# известные формы и открывал новые, потому что шаблон вынужден РЕШАТЬ вопросы
# синтаксиса оболочки, не разбирая его: маркер документа внутри кавычек или
# в комментарии принимался за настоящий и вырезал следующую команду; деление
# по `;` резало содержимое кавычек; подстановка, которую исполняет хост,
# отбрасывалась вместе с аргументами контейнера.
#
# Здесь команда сначала разбирается на токены, и только потом принимаются
# решения. Кавычки, комментарии и экранирование становятся фактами разбора,
# а не догадкой шаблона.
#
# Граница честная: shlex — лексер, не парсер оболочки. Он не знает группировки,
# подоболочек и приоритетов. Поэтому решения опираются только на то, что он
# даёт надёжно: границы слов, кавычки, комментарии, операторы. Незнакомая
# конструкция трактуется в пользу ОТКАЗА — остаётся под проверкой, а не
# исчезает из неё.
# ─────────────────────────────────────────────────────────────────────────────

STAGE_OPS = {";", "&&", "||", "|", "&"}

# Подстановки исполняет ХОСТ, где бы они ни стояли — в том числе среди
# аргументов контейнера. Второй прогон ревью: команда контейнера с подстановкой,
# создающей файл снаружи, проходила границу, потому что вся стадия считалась
# контейнерной.
SUBSTITUTION = re.compile(r"\$\(([^()]*)\)|`([^`]*)`|<\(([^()]*)\)|>\(([^()]*)\)")

def tokenize(text):
    """Токены строки. Пустой список — признак того, что разобрать не удалось;
    вызывающий обязан считать такую команду неизвестной, а не безопасной.

    Перевод строки — такой же разделитель команд, как `;`, но shlex считает
    его пробелом. Поэтому он заменяется явным оператором ДО разбора: без
    этого `docker run img` и стоящая следующей строкой команда сливались
    в одну стадию, и контейнерное сужение прятало вторую. Регрессия,
    внесённая переходом на токены и пойманная третьим кругом внешнего ревью.
    """
    if not text:
        return []
    # Продолжение строки обратным слэшем оболочка склеивает — значит склеиваем
    # и мы, ДО разбора. Иначе первая половина заканчивается незавершённым
    # экранированием, лексер падает, и команда остаётся без единого кандидата.
    text = re.sub(r"\\\n", " ", text)
    out = []
    for idx, line in enumerate(text.split("\n")):
        if idx:
            out.append(";")             # перевод строки — разделитель команд
        lex = shlex.shlex(line, posix=True, punctuation_chars=True)
        lex.whitespace_split = True
        try:
            out.extend(lex)
        except ValueError:
            # Не разобрали — команда НЕИЗВЕСТНА, а не безопасна. Пустой список
            # здесь означал бы «путей нет» и разрешал команду: ровно тот
            # fail-open, который обещал не допускать соседний комментарий.
            # Возвращаем грубое разбиение: лишние кандидаты дешевле пропуска.
            out.extend(t for t in re.split(r"\s+", line) if t)
    return out

def substitutions(text):
    """Тела подстановок команд — они исполняются хостом."""
    out = []
    for m in SUBSTITUTION.finditer(text or ""):
        for group in m.groups():
            if group and group.strip():
                out.append(group.strip())
    return out

ENV_HOME = re.compile(r"\$\{HOME\}|\$HOME\b|\$\{?USERPROFILE\}?\b")
QUOTES = str.maketrans("", "", "\"'")
SPLIT = re.compile(r"[\s;|&()]+")
REDIRECT = re.compile(r"(?<![0-9<>])>>?\s*(?P<path>(?:[\"'][^\"']+[\"'])|[^\s;|&<>]+)")

# Признаки намерения записи. Список неполон принципиально — поэтому рядом
# стоит отдельная проверка встроенных интерпретаторов. Живёт здесь, а не в
# отдельном хуке, чтобы граница репозитория и защита файлов правил смотрели
# на команду одинаково: два разных списка разойдутся при первой же правке.
WRITE_INTENT = re.compile(
    r"(?<![0-9<>])>>?(?![>])"                                  # перенаправление вывода
    r"|\b(?:rm|rmdir|unlink|mv|cp|dd|truncate|shred|touch|mkdir|install|rsync|scp)\b"
    r"|\b(?:tee|ln)\b"
    r"|\b(?:chmod|chown|chgrp|xattr)\b"
    r"|\bsed\b[^|;&]*\s-i\b|\bperl\b[^|;&]*\s-[a-z]*i[a-z]*\b"
    r"|\bcurl\b[^|;&]*\s-(?:o|-output)\b|\bwget\b[^|;&]*\s-(?:O|-output-document)\b"
    r"|\bgit\s+(?:clone|init|worktree\s+add)\b"
    r"|\bpatch\b|\bapply\b[^|;&]*\.patch\b"
    # Ключи контейнерных команд, создающие файлы НА ХОСТЕ: идентификатор
    # контейнера, идентификатор образа, выгрузка образа. Без них стадия
    # выглядела как «ничего не пишет», и путь хоста, уже собранный разбором,
    # до проверки не доходил. Второй круг внешнего ревью.
    r"|--(?:cidfile|iidfile|output|iid)\b|\bdocker\s+(?:save|export)\b"
    # Том, примонтированный БЕЗ `:ro`, даёт контейнеру запись в каталог хоста.
    # Это способ писать наружу, и его надо считать намерением записи — иначе
    # путь, уже правильно собранный разбором, до проверки не доходит.
    # Четвёртый круг внешнего ревью.
    r"|(?:-v|--volume|--mount)[=\s][^\s]*(?<!:ro)(?<!:ro,z)(?:\s|$)",
    re.I)

# Встроенный код нельзя разобрать регуляркой: если он упоминает защищённый путь
# или путь наружу, считаем это записью. Ложный отказ дешевле пропущенной записи.
_INLINE_RE = re.compile(
    r"\b(?:python[\d.]*|python3)\s+-c\b|\bnode\s+-e\b|\bperl\s+-[a-z]*e\b"
    r"|\bruby\s+-e\b|\bphp\s+-r\b|\bosascript\b|\bawk\b[^|;&]*\bprint\s*>"
    # Код, поданный интерпретатору документом (`python3 - <<'PY'`, `bash <<'SH'`),
    # — тот же встроенный код, только другой формы. Без этой строки тело
    # оставалось в команде (см. heredoc_body_is_data), но хук выходил раньше,
    # чем до него добирался: ни перенаправления, ни знакомой команды записи
    # в строке нет. Найдено на ревью PR #53 (issue #43).
    # Обёртки (`env -i`, `timeout 10`, `exec`, `nice`) отодвигают имя
    # интерпретатора от начала стадии. Без их учёта тело документа оставалось
    # в команде, но хук выходил раньше, чем до него доходил: ни перенаправления,
    # ни знакомой команды записи в строке нет. Подтверждено запуском.
    # Разделитель `--` между обёрткой и командой тоже отодвигает имя:
    # `env -- python3 - <<PY` проходил мимо. Второй круг внешнего ревью.
    r"|(?:^|[;&|]\s*)(?:(?:sudo(?:\s+-\w+(?:\s+\S+)?)*|env(?:\s+-\w+)*(?:\s+\w+=\S+)*"
    r"|command|exec|nice|ionice|timeout(?:\s+-\w+)*\s+\S+|stdbuf(?:\s+-\S+)*|nohup"
    r"|setsid|busybox|time|uv\s+run|npx|bunx|\w+=\S+|--)\s+)*"
    r"(?:\S*/)?(?:(?:ba|z|k|da|c|fi)?sh|python[\d.]*|node|deno|bun"
    r"|perl|ruby|php|osascript|lua|Rscript|tclsh|pwsh)\b[^\n]*<<",
    re.I)

class _InlineCode:
    """Признак встроенного кода. Не регулярка, а объект с тем же методом —
    хуки продолжают звать `INLINE_CODE.search(...)` и менять их не пришлось.

    Помимо известных форм (`python3 -c`, `node -e`) сюда попадает ЛЮБОЙ
    документ, тело которого не признано данными: разбор получателя идёт
    по токенам, поэтому незнакомый интерпретатор (`pypy3`, собственный
    скрипт) больше не проходит мимо только из-за отсутствия в перечне.
    Третий круг внешнего ревью: тело сохранялось верно, но проверка
    выходила раньше, чем до него доходила.
    """

    def search(self, text):
        m = _INLINE_RE.search(text or "")
        if m:
            return m
        for line in (text or "").split("\n"):
            if heredoc_delimiter(line) and not heredoc_body_is_data(line):
                return line
        return None

INLINE_CODE = _InlineCode()


def normalize(text):
    """Разворачивает $HOME и ~, снимает кавычки, вырезает тела heredoc.
    Строка становится сравнимой.

    Вырезание heredoc живёт здесь, а не в каждом хуке отдельно: на команду
    смотрят трое (граница репозитория, защита файлов правил, защита истории),
    и текст, который команда пишет в файл, для всех троих одинаково является
    данными. Иначе один и тот же класс ложных тревог пришлось бы чинить
    в трёх местах — и он уже проявился в двух (issue #43, случаи 7 и 8).
    """
    if not text:
        return ""
    out = strip_heredocs(text)
    out = ENV_HOME.sub(HOME, out)
    out = out.translate(QUOTES)
    out = re.sub(r"(?:^|(?<=[\s=:]))~(?=/|$)", HOME, out)
    return out

def resolve(path, root):
    """Абсолютный путь, куда команда попадёт на самом деле."""
    expanded = os.path.expanduser(normalize(path))
    if not os.path.isabs(expanded):
        expanded = os.path.join(root, expanded)
    return os.path.realpath(expanded)

# Токен из одних цифр и слэшей — арифметика, а не путь: `//60` внутри
# python3 -c читался как абсолютный путь и получал отказ. Отбрасывается только
# то, что не начинается с точки или тильды, поэтому `../2` и `./7` остаются
# путями и проверяются: сосед по имени из цифр — обычное дело.
# Обязательна хотя бы одна цифра. Без этого требования шаблон совпадал
# с голым слэшем — и корень файловой системы отбрасывался как «арифметика»
# ещё до всякой проверки. Вторая половина того же блокера, что и с glob:
# правило против ложной тревоги молча накрыло самый опасный путь.
DIGITS_ONLY = re.compile(r"^/*\d+(?:/*\d+)*/*$")

# Токен из одних звёздочек — glob-шаблон, а не путь. Ведущий слэш сюда
# не входит, и это принципиально.
#
# Первая версия правила накрывала и слэши. Она стоила блокера: под неё
# попадали корень файловой системы и любой шаблон от него, поэтому команды,
# удаляющие или меняющие права от корня, объявляли свою цель «не путём»
# и получали разрешение. Правило задумывалось против шаблона, встреченного
# как строка внутри скрипта (случай 3 задачи #43), — и вместе с ним сняло
# проверку ровно там, ради чего механизм существует.
#
# Нашло внешнее ревью, подтверждено запуском хуков. Цена нового правила
# названа честно: тот же шаблон как ДАННЫЕ внутри встроенного кода снова
# даёт ложный отказ. Записано в docs/HOOKS.md — отказ на безобидном дешевле
# разрешения стереть корень.
GLOB_ONLY = re.compile(r"^\*+$")

# Тело heredoc — данные, которые команда ПИШЕТ, а не путь, по которому она
# пишет. Четыре из восьми ложных отказов issue #43 — отсюда: текст задания,
# журнальная запись, тело PR, комментарий с путём в прозе. Тот же разбор уже
# стоял в guard-git (issue #20) — здесь он вынесен в общий модуль, чтобы
# граница репозитория и защита файлов правил смотрели на команду одинаково.
#
# Понимает одиночный `<<DELIM` / `<<-DELIM` / `<<'DELIM'` / `<<"DELIM"` на
# строку. Несколько heredoc в одной команде и вложенные — не разбирает: тогда
# текст просто не вырезается, то есть худший исход — прежний ложный отказ,
# а не пропуск записи.
HEREDOC_OPEN = re.compile(r"<<-?\s*(['\"]?)([A-Za-z_][A-Za-z0-9_]*)\1")

# Тело heredoc — данные ТОЛЬКО если получатель его записывает (`cat > file`,
# `gh pr create --body-file -`). Если получатель — интерпретатор, тело
# ИСПОЛНЯЕТСЯ, и вырезать его значит убрать из проверки настоящий код.
# Найдено на ревью PR #53 (issue #43): `python3 - <<'PY' … PY` писал наружу,
# `bash <<'SH'` удалял наружу, а через `guard-secrets` тем же приёмом читался
# `.env` — то есть обход, ради которого хук и заведён, менял форму и проходил.
# Проверяется первый токен строки-открывашки и токены после конвейера: важна
# позиция команды, а не упоминание слова (`cat > bash-notes.md <<'EOF'` пишет
# файл, а не исполняет).
# Обёртки перед именем интерпретатора распознаются отдельно. Первая версия
# ждала имя почти сразу после начала стадии, и внешнее ревью показало, чем
# это кончается: обёртки отодвигали имя, тело исполнялось, но считалось
# данными. Подтверждено запуском.
#
# Список обёрток и интерпретаторов принципиально неполон — поэтому он стоит
# на стороне безопасного исхода: не узнали интерпретатор, тело остаётся под
# проверкой (лишний отказ), а не исчезает из неё.
# Обёртки, которые стоят ПЕРЕД именем программы и её не меняют. Разбираются
# по токенам: имя обёртки, затем её собственные ключи, затем настоящая команда.
WRAPPERS = {
    "sudo", "env", "command", "exec", "nice", "ionice", "timeout", "stdbuf",
    "nohup", "setsid", "busybox", "xargs", "time", "npx", "bunx", "uv",
}

# Потребители, ИСПОЛНЯЮЩИЕ тело документа. Список неполон принципиально,
# поэтому решение построено от обратного: тело считается данными только когда
# получатель уверенно опознан как пишущий. Незнакомое имя оставляет тело
# под проверкой — лишний отказ дешевле пропущенного кода.
INTERPRETERS = {
    "sh", "bash", "zsh", "ksh", "dash", "csh", "fish", "ash",
    "node", "deno", "bun", "perl", "ruby", "php", "osascript", "awk",
    "lua", "rscript", "tclsh", "groovy", "pwsh", "powershell", "julia",
    "ts-node", "tsx", "make", "sqlite3", "psql", "mysql", "gdb", "jq",
}

# Получатели, которые тело ЗАПИСЫВАЮТ, а не исполняют. Решение построено
# от этого списка, а не от списка интерпретаторов: незнакомое имя оставляет
# тело под проверкой. Обратный порядок стоил дыры — `pypy3`, собственный
# скрипт, `eval` считались пишущими просто потому, что их не было в перечне
# интерпретаторов (третий круг внешнего ревью).
DATA_SINKS = {
    "cat", "tee", "gh", "git", "cp", "install", "dd", "sponge",
    "curl", "wget", "mail", "sendmail", "base64", "tr", "fold",
}

def command_word(tokens):
    """Имя программы стадии: пропускает обёртки, их ключи, присваивания
    переменных и разделитель `--`. Возвращает пустую строку, если не нашлось."""
    i = 0
    while i < len(tokens):
        tok = tokens[i]
        if tok in STAGE_OPS or tok == "--":
            i += 1
            continue
        if "=" in tok and not tok.startswith("-") and "/" not in tok.split("=")[0]:
            i += 1                      # VAR=value перед командой
            continue
        if tok.startswith("-"):
            i += 1                      # ключ обёртки
            continue
        name = os.path.basename(tok).lower()
        if name in WRAPPERS:
            i += 1
            # у timeout первый неключевой аргумент — длительность
            if name == "timeout":
                while i < len(tokens) and tokens[i].startswith("-"):
                    i += 1
                i += 1
            continue
        return name
    return ""

def heredoc_body_is_data(opening_line):
    """True, если тело документа получатель запишет, а не исполнит.

    Разбор по токенам, а не по шаблону: до перехода на них имя программы
    искалось почти сразу после начала стадии, и обёртки (`env -i`,
    `timeout 10`, `exec`, разделитель `--`) его отодвигали — тело исполнялось,
    но считалось данными. Найдено двумя кругами внешнего ревью.
    """
    toks = tokenize(opening_line)
    if not toks:
        return False                    # не разобрали — не вырезаем

    # Конвейер: тело уходит на stdin ПОСЛЕДНЕЙ команды, а не первой.
    # `cat <<'EOF' | bash` — документ для bash, а не для cat. Третий круг
    # внешнего ревью: тело вырезалось как данные и код исчезал из проверки.
    if "|" in toks:
        return False                    # получателя не разобрать — не вырезаем

    name = command_word(toks)
    if not name:
        return False

    # Тело считается данными, только когда получатель УВЕРЕННО опознан как
    # пишущий. Прежняя проверка была от обратного — «нет в списке
    # интерпретаторов, значит пишет», — и противоречила собственному
    # комментарию о безопасном исходе: незнакомое имя (`pypy3`, свой скрипт,
    # `eval`) уносило тело из проверки. Найдено третьим кругом ревью.
    base = re.sub(r"[\d.]+$", "", name)
    return name in DATA_SINKS or base in DATA_SINKS

def strip_heredocs(command):
    """Команда без тел heredoc-документов: остаётся то, что она исполняет.

    Вырезается только ЗАКРЫТЫЙ документ — тот, у которого найдена метка конца.
    Открытая метка без закрывающей оставляется как есть: иначе всё до конца
    команды считалось бы данными, и настоящая команда, идущая следом, исчезала
    бы из проверки. Это не теория — поймано парным тестом issue #43 на второй
    же минуте: `cat > f <<'EOF' … EOF`, а следом `echo x > ../../outside/file`
    проходили как безобидные, потому что функция применялась дважды и на
    втором проходе закрывающей метки уже не было.

    Как следствие функция идемпотентна: повторный прогон ничего не меняет.
    """
    if "<<" not in command:
        return command
    lines = command.split("\n")
    out = []
    i = 0
    while i < len(lines):
        line = lines[i]
        out.append(line)
        delim = heredoc_delimiter(line)
        i += 1
        if not delim:
            continue
        if not heredoc_body_is_data(line):
            continue          # тело исполняется — оставляем его под проверку
        end = i
        while end < len(lines) and lines[end].strip() != delim:
            end += 1
        if end >= len(lines):
            continue          # метка конца не найдена — тело не вырезаем
        # Метка в кавычках (`<<'EOF'`) отключает подстановки — тело буквально
        # данные. Без кавычек оболочка исполняет `$(...)` и обратные кавычки
        # ДО того, как получатель их запишет: `cat > f <<EOF` с подстановкой,
        # удаляющей каталог, вырезался целиком и удаление исчезало из проверки.
        # Третий круг внешнего ревью. Поэтому у некавыченного документа
        # подстановки сохраняются, а остальное тело вырезается как данные.
        if not heredoc_delimiter_quoted(line):
            body = "\n".join(lines[i:end])
            for inner in substitutions(body):
                out.append(inner)
        i = end + 1           # пропустить тело вместе со строкой-меткой
    return "\n".join(out)

def heredoc_delimiter_quoted(line):
    """True, если метка документа взята в кавычки — тогда оболочка тело
    не трогает и оно действительно только данные."""
    m = re.search(r"<<-?\s*(['\"])", line)
    return bool(m)

def heredoc_delimiter(line):
    """Метка документа, если строка ДЕЙСТВИТЕЛЬНО его открывает.

    Оператор ищется среди токенов. До перехода на них шаблон принимал за
    открывающий и маркер внутри кавычек (`echo '<<EOF'`), и в комментарии
    (`echo ok # <<EOF`) — и вырезал тело несуществующего документа вместе
    с настоящей командой, стоявшей следом. Это был пропуск, а не шум:
    удаление за пределами репозитория исчезало из проверки. Найдено вторым
    кругом внешнего ревью, подтверждено запуском.
    """
    if "<<" not in line:
        return ""
    toks = tokenize(line)
    for i, tok in enumerate(toks):
        if tok in ("<<", "<<-") and i + 1 < len(toks):
            return toks[i + 1]
    return ""

# Пути после docker/podman относятся к файловой системе КОНТЕЙНЕРА и к границе
# хоста отношения не имеют (issue #43, случай 4). Единственное исключение —
# источник тома: в `-v /host/path:/container/path` левая половина реальна,
# и её проверять обязательно, иначе сужение стало бы дырой.
# Проверяется НАЧАЛО стадии, а не вся команда. Первая версия искала docker
# по всей строке и, найдя, сужала разбор целиком: `docker compose up -d &&
# rm -rf <наружу>` проходил границу — удаление оказывалось «аргументом
# контейнера». Найдено на ревью PR #53 (issue #43).
CONTAINER_CMD = re.compile(r"^\s*(?:sudo\s+)?(?:docker|podman)\s+", re.I)

# Границы стадий: каждая проверяется отдельно, чтобы сужение одной стадии
# не распространялось на соседние.
STAGE_SPLIT = re.compile(r"\|\||&&|[;&|\n]")
VOLUME_FLAG = re.compile(r"(?:^|\s)(?:-v|--volume|--mount)(?:=|\s+)(?P<spec>[^\s]+)")

# Флаги docker/podman, аргумент которых — путь ХОСТА, а не контейнера.
# Внешнее ревью показало, что «всё после docker — контейнерное» неверно:
# контекст сборки, файл сборки, файлы compose, env-file, образы для load/save
# живут на хосте. `docker build /outside/context` и `docker cp x /outside/file`
# проходили границу — подтверждено запуском.
HOST_PATH_FLAG = re.compile(
    r"(?:^|\s)(?:-f|--file|-c|--config|--env-file|--secret|--build-context"
    r"|-i|--input|-o|--output|--cache-from|--cache-to|--iidfile|--contextdir)"
    r"(?:=|\s+)(?P<path>[^\s]+)", re.I)

# Подкоманды, у которых позиционный аргумент — путь хоста.
HOST_POSITIONAL = re.compile(
    r"^\s*(?:sudo\s+)?(?:docker|podman)\s+(?:image\s+|buildx\s+)?"
    r"(?P<sub>build|cp|load|save|import|export)\b(?P<rest>.*)", re.I | re.S)

def container_scope(command):
    """(есть ли docker-команда, пути-источники томов). Пути внутри контейнера
    в кандидаты не попадают — но пути хоста попадают: тома, файлы сборки,
    контекст, источники и цели копирования."""
    if not CONTAINER_CMD.search(command):
        return False, []
    sources = []
    for m in HOST_PATH_FLAG.finditer(command):
        sources.append(m.group("path"))
    m = HOST_POSITIONAL.search(command)
    if m:
        # У `cp` путь хоста — тот аргумент, что без `контейнер:`; у остальных
        # позиционный аргумент относится к хосту целиком.
        for token in m.group("rest").split():
            if token.startswith("-"):
                continue
            if ":" in token and not token.startswith(("/", ".", "~")):
                continue          # `контейнер:/путь` — внутренность контейнера
            sources.append(token)
    for m in VOLUME_FLAG.finditer(command):
        spec = m.group("spec")
        if spec.startswith("type="):          # --mount type=bind,source=...
            for part in spec.split(","):
                if part.startswith(("source=", "src=")):
                    sources.append(part.split("=", 1)[1])
            continue
        head = spec.split(":", 1)[0]          # -v /host/path:/container/path
        if head:
            sources.append(head)
    return True, sources

# Ключи docker/podman, чей аргумент — путь ХОСТА. «Всё после docker —
# контейнерное» неверно: файлы сборки и конфигурации, тома, секреты, кеш,
# образы для загрузки и сохранения, идентификаторы контейнеров живут на хосте.
HOST_PATH_OPTS = {
    "-v", "--volume", "--mount", "-f", "--file", "-c", "--config",
    "--env-file", "--secret", "--build-context", "-i", "--input",
    "-o", "--output", "--cache-from", "--cache-to", "--iidfile",
    "--cidfile", "--label-file", "--authfile", "--security-opt",
    "--device", "--tlscacert", "--tlscert", "--tlskey", "--contextdir",
    "--ssh", "--metadata-file", "--project-directory", "--rootfs",
    "--env-file", "--certs-dir", "--storage-opt", "--runroot", "--root",
}

# Ключи, значение которых — составное: `type=bind,source=/host,target=/x`,
# `id=x,src=/host/key`, `type=local,dest=/host/out`, `default=/host/key`.
# Первая версия брала такой spec целиком, и абсолютный источник превращался
# в относительный путь «внутри репозитория» — то есть проверка сходилась
# не туда. Четвёртый круг внешнего ревью.
COMPOSITE_KEYS = ("source=", "src=", "dest=", "default=", "path=")

# Подкоманды, у которых позиционный аргумент — путь хоста.
HOST_POSITIONAL_SUBS = {"build", "cp", "load", "save", "import", "export"}


def host_paths_in_spec(spec):
    """Пути хоста внутри значения ключа docker/podman.

    Значение бывает составным (`type=bind,source=/host,target=/x`,
    `id=x,src=/host/key`, `type=local,dest=/host/out`, `default=/host/key`)
    и простым (`/host:/container`, `/host/path`). Первая версия брала составное
    целиком, и абсолютный источник превращался в относительный путь «внутри
    репозитория» — проверка сходилась не туда. Четвёртый круг внешнего ревью.
    """
    out = []
    if "," in spec or any(k in spec for k in COMPOSITE_KEYS):
        for part in spec.split(","):
            for key in COMPOSITE_KEYS:
                if part.startswith(key):
                    out.append(part.split("=", 1)[1])
                    break
        if out:
            return out
    if "=" in spec and not spec.startswith(("/", ".", "~")):
        return [spec.split("=", 1)[1].split(":", 1)[0]]
    return [spec.split(":", 1)[0]]

def container_scope_tokens(tokens):
    """(контейнерная ли стадия, пути хоста в ней). Разбор по токенам.

    Пути внутри контейнера в кандидаты не попадают, пути хоста — попадают.
    Список ключей неполон принципиально: неизвестный ключ со значением-путём
    трактуется в пользу отказа только там, где значение похоже на путь хоста.
    """
    name = command_word(tokens)
    if name not in ("docker", "podman"):
        return False, []
    host = []
    sub = ""
    i = 0
    while i < len(tokens):
        tok = tokens[i]
        if tok in HOST_PATH_OPTS and i + 1 < len(tokens):
            host.extend(host_paths_in_spec(tokens[i + 1]))
            i += 2
            continue
        if "=" in tok and tok.split("=", 1)[0] in HOST_PATH_OPTS:
            host.extend(host_paths_in_spec(tok.split("=", 1)[1]))
            i += 1
            continue
        if not sub and tok.lower() in HOST_POSITIONAL_SUBS:
            sub = tok.lower()
            i += 1
            continue
        i += 1
    if sub:
        # У `cp` путь хоста — аргумент без `контейнер:`; у остальных подкоманд
        # позиционный аргумент относится к хосту.
        seen_sub = False
        for tok in tokens:
            if tok.lower() == sub and not seen_sub:
                seen_sub = True
                continue
            if not seen_sub or tok.startswith("-") or tok in STAGE_OPS:
                continue
            if ":" in tok and not tok.startswith(("/", ".", "~")):
                continue          # `контейнер:/путь`
            host.append(tok)
    return True, host

def path_candidates(command):
    """Всё, что в команде похоже на путь: аргументы, цели перенаправления.

    Из разбора исключается то, что путём не является: тела heredoc (данные),
    glob-токены и — для docker/podman — пути внутри контейнера, кроме
    источников примонтированных томов.
    """
    normalized = normalize(command)          # уже без тел «пишущих» heredoc
    found = []

    # Подстановки исполняет ХОСТ, где бы они ни стояли, — в том числе среди
    # аргументов контейнера. Разбираются рекурсивно и ДО контейнерного сужения:
    # иначе `docker run img "$(touch <наружу>)"` проходил границу, потому что
    # вся стадия объявлялась контейнерной. Второй круг внешнего ревью.
    for inner in substitutions(normalized):
        found.extend(path_candidates(inner))

    # Разбор постадийный: сужение, законное для одной стадии, не должно
    # распространяться на соседнюю. Границы стадий берутся из ТОКЕНОВ, поэтому
    # `;` внутри кавычек (`sh -c "echo /app; ls /tmp/x"`) стадию не разрывает —
    # до перехода на токены это давало ложные срабатывания на аргументах,
    # предназначенных контейнеру.
    for stage_tokens in split_stages(tokenize(normalized)):
        if not stage_tokens:
            continue
        # Перенаправления реальны в любой стадии, включая docker: вывод пишется
        # на хост, а не в контейнер.
        i = 0
        while i < len(stage_tokens):
            if stage_tokens[i] in (">", ">>") and i + 1 < len(stage_tokens):
                found.append(stage_tokens[i + 1])
                i += 2
                continue
            i += 1
        is_container, host_paths = container_scope_tokens(stage_tokens)
        if is_container:
            # Остальные аргументы описывают файловую систему контейнера;
            # проверять в ней нечего. Пути хоста собраны отдельно.
            found.extend(host_paths)
            continue
        for token in stage_tokens:
            if token in STAGE_OPS or token in (">", ">>", "<", "<<", "<<-"):
                continue
            if not token or token.startswith("-"):
                continue
            if DIGITS_ONLY.match(token) or GLOB_ONLY.match(token):
                continue
            if "/" in token or token in (".", ".."):
                found.append(token)
    return found

def split_stages(tokens):
    """Токены, разбитые по операторам верхнего уровня."""
    stages, current = [], []
    for tok in tokens:
        if tok in STAGE_OPS:
            stages.append(current)
            current = []
        else:
            current.append(tok)
    stages.append(current)
    return stages
